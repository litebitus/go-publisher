package fielddescriptions

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

const mockImportPath = "github.com/litebitus/mock/described"

// The exported types' and fields' comments are read by their qualified names,
// each comment as one paragraph, and nothing undescribed or unexported is.
func TestExtractReadsTheExportedDocComments(t *testing.T) {
	descriptions, err := Extract("testdata/described", mockImportPath)
	require.NoError(t, err)
	require.Equal(t, map[string]string{
		mockImportPath + ".MockSettings":           "MockSettings are a mock section, described over two lines.",
		mockImportPath + ".MockSettings.Directory": "The mock directory, as `dir`.",
	}, descriptions)
}

// The source is a formatted Go file holding every description by name.
func TestSourceIsTheDescriptionsAsGo(t *testing.T) {
	source, err := Source("mock", "mock generator", map[string]string{
		"mock.B": "Second, with a \"quote\".",
		"mock.A": "First.",
	})
	require.NoError(t, err)
	text := string(source)
	require.True(t, strings.HasPrefix(text, "// Code generated by mock generator; DO NOT EDIT.\n"))
	require.Less(t, strings.Index(text, `"mock.A"`), strings.Index(text, `"mock.B"`))
	require.Contains(t, text, `"mock.B": "Second, with a \"quote\".",`)
	_, err = parser.ParseFile(token.NewFileSet(), "mock.go", source, parser.AllErrors)
	require.NoError(t, err)
}

func TestExtractNamesAFolderItCannotRead(t *testing.T) {
	_, err := Extract("testdata/mock-missing", mockImportPath)
	require.ErrorContains(t, err, "testdata/mock-missing")
}
