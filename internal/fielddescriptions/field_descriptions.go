// Package fielddescriptions reads the doc comments of a package's types and
// fields, the descriptions its JSON Schema carries, and writes them as Go
// source, so a schema is generated with them where the source is not at hand.
package fielddescriptions

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/invopop/jsonschema"
)

// Extract reads the doc comments of the exported types and fields in the
// package at dir, imported as importPath, keyed as a reflector's CommentMap
// keys them: `<importPath>.<Type>` and `<importPath>.<Type>.<Field>`. A comment
// wrapped over several lines reads as one paragraph.
func Extract(dir, importPath string) (map[string]string, error) {
	reflector := jsonschema.Reflector{}
	if err := reflector.AddGoComments(importPath, dir, jsonschema.WithFullComment()); err != nil {
		return nil, fmt.Errorf("failed to read the doc comments in %s: %w", dir, err)
	}
	// The reflector names a package by importPath joined with dir; the package's
	// own names are kept, under importPath, and any subpackage's are not.
	walkedPackage := path.Join(importPath, filepath.ToSlash(dir)) + "."
	descriptions := make(map[string]string, len(reflector.CommentMap))
	for name, comment := range reflector.CommentMap {
		qualified, isOwn := strings.CutPrefix(name, walkedPackage)
		description := strings.Join(strings.Fields(comment), " ")
		if isOwn && description != "" {
			descriptions[importPath+"."+qualified] = description
		}
	}
	return descriptions, nil
}

// Source is the Go file of package packageName holding descriptions as the
// variable FieldDescriptions, in name order.
func Source(packageName, generator string, descriptions map[string]string) ([]byte, error) {
	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by %s; DO NOT EDIT.\n\n", generator)
	fmt.Fprintf(&source, "package %s\n\n", packageName)
	source.WriteString("// FieldDescriptions are the doc comments of the configuration's types and\n")
	source.WriteString("// fields, by fully qualified name, the descriptions its JSON Schema carries.\n")
	source.WriteString("var FieldDescriptions = map[string]string{\n")
	for _, name := range slices.Sorted(maps.Keys(descriptions)) {
		fmt.Fprintf(&source, "%s: %s,\n", strconv.Quote(name), strconv.Quote(descriptions[name]))
	}
	source.WriteString("}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format the generated descriptions: %w", err)
	}
	return formatted, nil
}
